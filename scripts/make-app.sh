# Build Tapecut.app, a launcher for the browser UI.
#
#   scripts/make-app.sh                  # /Applications (else ~/Applications)
#   scripts/make-app.sh ~/Applications   # or somewhere else
#
# The app is a thin wrapper around this checkout: clicking it starts
# `venv/bin/python -m web.server` if nothing is answering yet, then opens the
# page. It runs whatever code is here, so rebuild only if the folder moves.
# The checkout's path is written into the built app, never into the repo.
set -euo pipefail

PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
# /Applications is writable for admin accounts; standard accounts get their own
DEST_DIR="${1:-/Applications}"
[ -n "${1:-}" ] || [ -w "$DEST_DIR" ] || DEST_DIR="$HOME/Applications"
APP="$DEST_DIR/Tapecut.app"
BUNDLE_ID="io.github.bravethea.tapecut"

[ -x "$PROJECT/venv/bin/python" ] || {
    echo "No venv in $PROJECT — set it up first (see README, Install)." >&2
    exit 1
}
mkdir -p "$DEST_DIR"

# Replace an earlier build, but never something else that happens to be
# called Tapecut.app.
if [ -e "$APP" ]; then
    existing="$(defaults read "$APP/Contents/Info" CFBundleIdentifier 2>/dev/null || true)"
    if [ "$existing" != "$BUNDLE_ID" ]; then
        echo "$APP exists and isn't a Tapecut launcher; not touching it." >&2
        exit 1
    fi
    rm -rf "$APP"
fi

mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>               <string>Tapecut</string>
    <key>CFBundleDisplayName</key>        <string>Tapecut</string>
    <key>CFBundleIdentifier</key>         <string>$BUNDLE_ID</string>
    <key>CFBundleExecutable</key>         <string>Tapecut</string>
    <key>CFBundleIconFile</key>           <string>Tapecut</string>
    <key>CFBundlePackageType</key>        <string>APPL</string>
    <key>CFBundleShortVersionString</key> <string>1.0</string>
    <key>LSMinimumSystemVersion</key>     <string>12.0</string>
    <!-- The launcher exits as soon as the page is open; without this its
         Dock icon would bounce and vanish on every click. -->
    <key>LSUIElement</key>                <true/>
</dict>
</plist>
PLIST

# The launcher itself. Unquoted heredoc: only PROJECT is substituted now,
# everything escaped with \$ is evaluated when the app runs.
cat > "$APP/Contents/MacOS/Tapecut" <<LAUNCHER
#!/bin/bash
# Generated by scripts/make-app.sh — rebuild rather than edit.
PROJECT="$PROJECT"
URL="http://127.0.0.1:8756"
LOG="\$HOME/Tapecut/logs/server.log"

up() { curl -s -o /dev/null --max-time 1 "\$URL/"; }

fail() {
    osascript -e "display alert \"Tapecut couldn't start\" message \"\$1\" as critical" >/dev/null
    exit 1
}

if ! up; then
    [ -x "\$PROJECT/venv/bin/python" ] ||
        fail "No Tapecut checkout at \$PROJECT. If you moved it, run scripts/make-app.sh again."
    mkdir -p "\$(dirname "\$LOG")"
    # Keep one previous log rather than growing forever.
    [ -f "\$LOG" ] && [ "\$(stat -f %z "\$LOG")" -gt 5000000 ] && mv "\$LOG" "\$LOG.1"
    echo "--- started \$(date) ---" >> "\$LOG"
    cd "\$PROJECT"
    # Through a login shell, because apps opened from Finder get a bare PATH:
    # no Homebrew (ffmpeg, rclone) and no ~/.local/bin (claude), and none of
    # the variables set in the shell profile.
    PYTHONUNBUFFERED=1 nohup "\${SHELL:-/bin/zsh}" -lic 'exec venv/bin/python -m web.server' \
        >> "\$LOG" 2>&1 < /dev/null &
    for _ in \$(seq 60); do up && break; sleep 0.5; done
    up || fail "The server didn't answer within 30 seconds. Details are in ~/Tapecut/logs/server.log."
fi

open "\$URL"
LAUNCHER
chmod +x "$APP/Contents/MacOS/Tapecut"

# Icon: draw one PNG, scale it to the sizes an .icns wants.
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
"$PROJECT/venv/bin/python" "$PROJECT/scripts/app_icon.py" "$tmp/icon.png"
set_dir="$tmp/Tapecut.iconset"
mkdir "$set_dir"
for size in 16 32 128 256 512; do
    sips -z $size $size "$tmp/icon.png" --out "$set_dir/icon_${size}x${size}.png" >/dev/null
    double=$((size * 2))
    sips -z $double $double "$tmp/icon.png" --out "$set_dir/icon_${size}x${size}@2x.png" >/dev/null
done
iconutil -c icns "$set_dir" -o "$APP/Contents/Resources/Tapecut.icns"

# Make Finder and the Dock pick up the new icon now, not after a re-login.
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" 2>/dev/null || true

echo "Built $APP"
echo "Open it from Launchpad or Spotlight; drag it to the Dock to keep it there."
